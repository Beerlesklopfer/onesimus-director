#!/bin/sh
# Writes THIRD-PARTY-RUST.txt (licence texts of all Rust dependencies from registries) into the repository root.
# The own crates (path dependencies, AGPL) are left out: their licence is LICENSE and Cargo.toml.
# Needs: cargo install cargo-about --locked --features cli
set -eu
cd "$(dirname "$0")/../.."
raw=$(mktemp)
trap 'rm -f "$raw"' EXIT
cargo about generate --workspace --config scripts/licenses/about.toml scripts/licenses/about.hbs -o "$raw"
python3 -I - "$raw" THIRD-PARTY-RUST.txt <<'PY'
import sys, re
raw = open(sys.argv[1], encoding="utf-8").read()
sections = []
for block in raw.split("@@SECTION ")[1:]:
    head, _, rest = block.partition("\n")
    crates_part, _, text = rest.partition("@@TEXT\n")
    crates = [l[len("@@CRATE "):].replace(" @@EXT", "") for l in crates_part.splitlines() if l.startswith("@@CRATE ") and "@@EXT" in l]
    if crates:
        sections.append((head.strip(), crates, text.strip("\n")))
sections.sort(key=lambda s: (-len(s[1]), s[0]))
out = ["Rust dependencies of the Onesimus binaries (odir, ofd, osd, oconsole, tools)",
       "=============================================================================", "",
       "Generated by scripts/licenses/make-third-party.sh with cargo-about from Cargo.lock;",
       "do not edit by hand. The own crates of this repository are not listed (see LICENSE).",
       "Each licence text below is followed by the crates that carry exactly this text.", "", "Overview", "--------"]
totals = {}
for head, crates, _ in sections:
    totals[head] = totals.get(head, 0) + len(crates)
for head, n in sorted(totals.items(), key=lambda kv: -kv[1]):
    out.append(f"{head}: {n} crate(s)")
for head, crates, text in sections:
    out += ["", "=" * 80, head, "=" * 80, "", "Used by:"] + [f" - {c}" for c in crates] + ["", text]
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
PY
