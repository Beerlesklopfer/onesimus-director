#!/usr/bin/env python3
"""Generate configure help exactly from the pinned Bareos ResourceItem tables.

Run against the original source checkout; --check rejects stale generated Rust.
TLS macro expansions and Messages items are read from their original headers.
Aliases are deliberately excluded: CmdlineItem formats only item.name.
"""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path
from generate_director_reference import COMMIT, TAG, clean, literal, table

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'crates/onesimus-dird/src/commands/configure_usage.rs'
SOURCES = ('core/src/dird/dird_conf.cc', 'core/src/lib/tls_resource_items.h',
           'core/src/lib/messages_resource_items.h', 'core/src/lib/res.cc',
           'core/src/lib/resource_item.h')


def generate(source):
    head = subprocess.check_output(['git', '-C', str(source), 'rev-parse', 'HEAD'], text=True).strip()
    if head != COMMIT:
        raise ValueError(f'Expected upstream commit {COMMIT}, got {head}')
    if subprocess.check_output(['git', '-C', str(source), 'status', '--porcelain', '--', *SOURCES], text=True):
        raise ValueError('Original source inputs must be clean')
    files = {name: (source / name).read_text() for name in SOURCES}
    dird = clean(files[SOURCES[0]])
    tls = clean(files[SOURCES[1]]).replace('\\\n', '')
    for name in ('TLS_COMMON_CONFIG', 'TLS_CERT_CONFIG'):
        macro = re.search(r'^#define\s+' + name + r'\(res\)\s+([^\n]*)', tls, re.M)
        if not macro:
            raise ValueError(f'Missing TLS macro {name}')
        dird = re.sub(name + r'\([^)]*\)', lambda _: macro[1], dird)
    # USER_ACL (the CFG_TYPE_ACL directives) and ACL_PROFILE are defined in
    # dird_conf.cc itself; expand their uses inside the item tables.
    joined = dird.replace('\\\n', '')
    for name in ('USER_ACL', 'ACL_PROFILE'):
        macro = re.search(r'^#define\s+' + name + r'\([^)]*\)\s+([^\n]*)', joined, re.M)
        if not macro:
            raise ValueError(f'Missing macro {name}')
        dird = re.sub(r'(?<!#define )\b' + name + r'\([^)]*\)', lambda _: macro[1], dird)
    datatypes = {fields[0]: literal(fields[1]) for fields, _ in table(clean(files[SOURCES[3]]), 'datatype_names') if fields[0] != '0'}
    messages = clean(files[SOURCES[2]])
    lines = []
    counts = []
    for fields, _ in table(dird, 'dird_resource_tables'):
        if fields[0] == 'nullptr' or fields[2] == 'NULL' or fields[3] == 'R_DIRECTOR':
            continue
        name = literal(fields[0]).lower()
        items = table(messages if fields[2] == 'msgs_items' else dird, fields[2])
        usage = 'add ' + name
        count = 0
        for item, _ in items:
            if not item:
                continue
            if len(item) != 4:
                raise ValueError(f'Unexpected item shape {item}')
            flags = item[3]
            if 'config::DeprecatedSince' in flags or 'config::UsesNoEquals' in flags:
                continue
            required = 'config::Required' in flags
            directive = literal(item[0]).lower()
            datatype = datatypes.get(item[1], 'unknown')
            usage += ' ' + ('' if required else '[') + f'{directive}=<{datatype}>' + ('' if required else ']')
            count += 1
        lines.append(usage + ' |\n')
        counts.append((name, count))
    lines.append('export client=<client>')
    hashes = [(name, hashlib.sha256((source / name).read_bytes()).hexdigest()) for name in SOURCES]
    out = '//! GENERATED by scripts/generate_configure_usage.py; do not edit.\n'
    out += f'//! Bareos {TAG}, commit {COMMIT}.\n'
    for name, digest in hashes:
        out += f'//! SHA256 {name}: {digest}\n'
    out += '\n/// Exact GetUsageStringForConsoleConfigureCommand / CmdlineItem output.\n'
    out += 'pub const USAGE: &str = concat!(\n'
    out += ''.join('    ' + json.dumps(line) + ',\n' for line in lines)
    out += ');\n\n#[cfg(test)]\nmod tests {\n    use super::USAGE;\n'
    out += '''    #[test]
    fn original_resource_order_required_markers_and_skipped_directives() {
        let resources: Vec<_> = USAGE.split(" |\\n").collect();
'''
    out += f'        assert_eq!(resources.len(), {len(counts)+1});\n'
    for i, (name, count) in enumerate(counts):
        out += f'        assert!(resources[{i}].starts_with("add {name} "));\n'
        out += f'        assert_eq!(resources[{i}].matches("=<").count(), {count});\n'
    out += '''        assert_eq!(*resources.last().unwrap(), "export client=<client>");
        let client = resources[0];
        assert!(client.contains(" name=<NAME>"));
        assert!(client.contains(" address=<STRING>"));
        assert!(client.contains(" password=<AUTOPASSWORD>"));
        assert!(client.contains(" [tlsenable=<BOOLEAN>]"));
        assert!(!client.contains("fileretention="));
        assert!(!client.contains("fdaddress="));
        assert!(!USAGE.contains("runscript="));
        assert!(!USAGE.contains("include="));
        assert!(!USAGE.contains("add director "));
        assert!(!USAGE.contains("add device "));
    }
}
'''
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate(args.source)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('configure_usage.rs is stale; regenerate it')
        print('configure usage matches pinned original sources')
    else:
        OUTPUT.write_text(content)
        print(f'generated {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
